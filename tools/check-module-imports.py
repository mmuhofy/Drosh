#!/usr/bin/env python3
"""
Check that every `dev.drosh.*` import is resolvable from the module that
holds the file.

The Kotlin compiler is the real authority, and CI runs it. This is the check
that runs *before* CI does: it answers "can this file see that type?" from the
manifests alone, which is where the answer went wrong three times in a row
during the guest-module move — a type moved to another module, and the import
that used to be implicit (same package) did not come with it.

For every module it reads:
  - the packages its own sources declare
  - the project dependencies it declares (`project(":x")`)
and then checks each file's imports against the union of those, plus the
packages of the modules it depends on.

Modules may be nested (`:features:agent` lives in `android/features/agent`),
so the module list is every directory with a `build.gradle.kts` in it, and a
module's name is its Gradle path with the colons turned into slashes.

Exit code 1 when something does not resolve.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = (
    Path(sys.argv[1]).resolve()
    if len(sys.argv) > 1
    else Path(__file__).resolve().parents[1] / "android"
)

IMPORT = re.compile(r"^import\s+(dev\.drosh\.[\w.]+)", re.M)
PROJECT_DEP = re.compile(r"""project\(\s*":([\w:.-]+)"\s*\)""")
PACKAGE = re.compile(r"^package\s+([\w.]+)", re.M)


def modules() -> dict[str, Path]:
    """Every module: its Gradle name (as a path) and its directory."""
    found: dict[str, Path] = {}
    for build in sorted(ROOT.rglob("build.gradle.kts")):
        if "/build/" in str(build):
            continue
        directory = build.parent
        name = str(directory.relative_to(ROOT))
        found[name] = directory
    return found


def packages_of(directory: Path) -> set[str]:
    """Every package the module's own sources declare."""
    found: set[str] = set()
    base = directory / "src"
    if not base.is_dir():
        return found
    for kt in base.rglob("*.kt"):
        found |= set(PACKAGE.findall(kt.read_text(encoding="utf-8", errors="ignore")))
    return found


def namespace_of(directory: Path) -> str:
    """The module's namespace — where its generated R class lives."""
    build = directory / "build.gradle.kts"
    if not build.is_file():
        return ""
    match = re.search(r'namespace\s*=\s*"([\w.]+)"', build.read_text(encoding="utf-8"))
    return match.group(1) if match else ""


def project_deps(directory: Path) -> set[str]:
    """The Gradle modules this one depends on."""
    build = directory / "build.gradle.kts"
    if not build.is_file():
        return set()
    return set(PROJECT_DEP.findall(build.read_text(encoding="utf-8")))


def main() -> int:
    mods = modules()
    own = {name: packages_of(d) for name, d in mods.items()}
    deps = {name: project_deps(d) for name, d in mods.items()}

    # A package belongs to the module that declares it. A package declared by
    # two modules is reported separately: that is a real ambiguity.
    owner: dict[str, set[str]] = {}
    for name, packages in own.items():
        for package in packages:
            owner.setdefault(package, set()).add(name)
        # The module's own namespace is its property even when no file declares
        # it as a package: the generated R class lives there.
        namespace = namespace_of(mods[name])
        if namespace:
            owner.setdefault(namespace, set()).add(name)

    problems: list[str] = []
    for name, directory in mods.items():
        visible = set(own[name])
        # The R class is generated by AGP, not written by hand, so it has no
        # source file to be found — but it is as visible as the module itself.
        namespace = namespace_of(directory)
        if namespace:
            visible.add(namespace)
        for dep in deps[name]:
            visible |= own.get(dep, set())
        for kt in (directory / "src").rglob("*.kt"):
            text = kt.read_text(encoding="utf-8", errors="ignore")
            for imported in IMPORT.findall(text):
                if imported in visible:
                    continue
                # A package is visible if the module that owns it is a
                # dependency, even when the exact package is not listed above
                # (a module may own several packages).
                owners = {
                    o
                    for package, o in owner.items()
                    if imported == package or imported.startswith(package + ".")
                    for o in o
                }
                if owners & (deps[name] | {name}):
                    continue
                problems.append(
                    f"{kt.relative_to(ROOT)}: {imported} is not visible from "
                    f":{name} (depends on {sorted(deps[name]) or 'nothing'})"
                )

    for problem in problems:
        print(problem)
    if problems:
        print(f"\n{len(problems)} unresolved import(s)")
        return 1
    print(f"all dev.drosh.* imports resolve from the module that holds the file "
          f"({len(mods)} modules)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
