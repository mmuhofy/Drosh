#!/usr/bin/env python3
"""Turn the brand icons in ``icons.txt`` into Android vector drawables.

Why this exists
---------------
A session card wears its program's own mark: a Python REPL, a `node` server, a
`vim` buffer and a `claude` prompt are four different things, and a grid of six
identical terminal outlines says nothing about any of them.

The marks come from Simple Icons (https://simpleicons.org, CC0-1.0). Each one is
a single-path SVG on a 24x24 viewBox, which is exactly what an Android vector
drawable is — so the conversion is a copy of the path data, not a rasterisation.
A bitmap would have needed five density buckets, could not be tinted to the
theme, and would be soft at any size it was not generated for.

Nothing here runs at build time. The generated XML is committed, so the APK
build needs no network and no Node; run this script only when the manifest
changes.

Usage
-----
    python3 tools/icons/fetch_icons.py            # fetch what is missing
    python3 tools/icons/fetch_icons.py --force    # re-fetch everything
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys
import urllib.error
import urllib.request
import xml.etree.ElementTree as ElementTree

# The manifest and the directory the drawables land in, relative to the repo.
ROOT = pathlib.Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "tools/icons/icons.txt"
OUTPUT_DIR = ROOT / "android/ui/src/main/res/drawable"

# Pinned: Simple Icons is an npm package, and an unpinned major would let a
# renamed slug silently break a card's icon on the next regeneration.
CDN = "https://cdn.jsdelivr.net/npm/simple-icons@16/icons/{slug}.svg"

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- {name} — from Simple Icons (https://simpleicons.org, CC0-1.0).
     Generated by tools/icons/fetch_icons.py; do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
{paths}
</vector>
"""

PATH = (
    '    <path\n'
    '        android:fillColor="#FFFFFFFF"\n'
    '        android:pathData="{data}" />\n'
)


def read_manifest() -> list[tuple[str, str]]:
    """The (program, slug) pairs, in file order and without duplicates."""
    pairs: list[tuple[str, str]] = []
    for line in MANIFEST.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        program, _, slug = line.partition("=")
        program, slug = program.strip(), slug.strip()
        if not program or not slug:
            print(f"manifest: skipping {line!r}", file=sys.stderr)
            continue
        pairs.append((program, slug))
    return pairs


def fetch(slug: str) -> str:
    with urllib.request.urlopen(CDN.format(slug=slug), timeout=30) as response:
        return response.read().decode("utf-8")


def paths_of(svg: str) -> list[str]:
    """The `d` attribute of every path in the SVG, in document order."""
    # The namespace is stripped because Simple Icons has shipped both with and
    # without it, and a namespaced tag would otherwise never match.
    body = re.sub(r'\sxmlns="[^"]*"', "", svg)
    root = ElementTree.fromstring(body)
    return [
        element.get("d")
        for element in root.iter("path")
        if element.get("d")
    ]


def drawable(name: str, paths: list[str]) -> str:
    return HEADER.format(
        name=name,
        paths="".join(PATH.format(data=data) for data in paths),
    )


def title_of(svg: str, fallback: str) -> str:
    match = re.search(r"<title>([^<]*)</title>", svg)
    return match.group(1) if match else fallback


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--force", action="store_true", help="re-fetch existing files")
    arguments = parser.parse_args()

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    fetched: dict[str, str] = {}
    written = 0
    missing: list[str] = []

    for program, slug in read_manifest():
        target = OUTPUT_DIR / f"brand_{slug}.xml"
        if target.exists() and not arguments.force:
            continue
        if slug not in fetched:
            try:
                fetched[slug] = fetch(slug)
            except urllib.error.HTTPError as error:
                print(f"missing: {slug} ({error.code}) — wanted by {program}", file=sys.stderr)
                missing.append(slug)
                continue
            except urllib.error.URLError as error:
                print(f"failed: {slug}: {error.reason}", file=sys.stderr)
                return 1
        svg = fetched[slug]
        data = paths_of(svg)
        if not data:
            print(f"no path: {slug}", file=sys.stderr)
            missing.append(slug)
            continue
        target.write_text(drawable(title_of(svg, slug), data), encoding="utf-8")
        written += 1

    print(f"wrote {written} drawable(s) to {OUTPUT_DIR.relative_to(ROOT)}")
    if missing:
        print(f"slugs without an icon: {', '.join(sorted(set(missing)))}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
